// Assemble dist/ for embedding: engine.js, lab.js, lab.css, and scenarios.js generated from scenarios/*.json.
// Every output is minified file by file with esbuild (no bundling, no source maps); engine/ and ui/ stay readable.
// Usage: node scripts/build.mjs [dist|site|test]   (default: dist)
//   dist  this repo's dist/
//   site  ../personal-website/public/lab, the website checkout next to this repo
//   test  dist-test/ (git-ignored), the generated modules the UI tests import
// Targets are fixed names, never paths, so the build cannot be pointed anywhere else.
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
// Resolve esbuild from this checkout's node_modules (run npm ci first).
const { transformSync } = createRequire(join(root, 'package.json'))('esbuild');
let out;
switch (process.argv[2] ?? 'dist') {
  case 'dist': out = join(root, 'dist'); break;
  case 'site': out = join(root, '..', 'personal-website', 'public', 'lab'); break;
  case 'test': out = join(root, 'dist-test'); break;
  default:
    console.error(`Unknown target "${process.argv[2]}"; use dist, site or test.`);
    process.exit(1);
}
mkdirSync(out, { recursive: true });

const scenarios = readdirSync(join(root, 'scenarios'))
  .filter(f => f.endsWith('.json'))
  .map(f => JSON.parse(readFileSync(join(root, 'scenarios', f), 'utf8')))
  .sort((a, b) => a.order - b.order)
  // The browser reads only these fields: expect is the test oracle and order is only the sort key.
  .map(({ id, title, summary, failures, safeguards, lesson }) => ({ id, title, summary, failures, safeguards, lesson }));

const execDir = join(root, 'executed');
const executed = {};
for (const f of readdirSync(execDir).filter(f => f.endsWith('.json') && f !== 'index.json')) {
  const x = JSON.parse(readFileSync(join(execDir, f), 'utf8'));
  const { scenarioId, generatedAt, runtime, timing, trace, record, dlq, dropped, buffered } = x;
  executed[scenarioId] = { generatedAt, runtime, timing, trace, record, dlq, dropped, buffered };
}
// Minify one module on its own: imports, exports and the lazy import('./executed.js') keep their shape.
const emit = (file, source) => {
  const loader = file.endsWith('.css') ? 'css' : 'js';
  writeFileSync(join(out, file), transformSync(source, { loader, minify: true, legalComments: 'none' }).code);
};
emit('scenarios.js',
  `// Generated by scripts/build.mjs from scenarios/*.json and executed/*.json IDs. Do not edit.\nexport const SCENARIOS = ${JSON.stringify(scenarios)};\nexport const RECORDING_IDS = ${JSON.stringify(Object.keys(executed))};\n`);
emit('executed.js',
  `// Generated by scripts/build.mjs from executed/*.json (recorded by the Java/Spring runner). Do not edit.
export const EXECUTED = ${JSON.stringify(executed)};
`);
emit('engine.js', readFileSync(join(root, 'engine', 'engine.js'), 'utf8'));
emit('lab.js', readFileSync(join(root, 'ui', 'lab.js'), 'utf8'));
emit('lab.css', readFileSync(join(root, 'ui', 'lab.css'), 'utf8'));
console.log(`Built ${scenarios.length} scenarios and ${Object.keys(executed).length} executed traces into ${out}`);
